"""Draws decompilation progress as an SVG map of the executable.

Every function of decomp/functions.tsv becomes a strip of cells, laid out in
address order (.text, then the .secu block), one cell per 256 bytes. The color
says what happened to it. A bar on top shows the measured percentages.

    python tools/progress_svg.py --svg docs/img/progress.svg
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tracking import ROOT, TRACK, load, measure  # noqa: E402

CELL_BYTES = 256
COLS = 128
CELL = 6
PAD = 16
HEADER = 96

# Same palette in light and dark viewers: mid-tone colors on a neutral grid.
COLORS = {
    "verified": "#2e9e5b",
    "readable": "#8fd19e",
    "replaced": "#4c8bf5",
    "dropped":  "#9aa0a6",
    "todo":     "#3a3f4b",
    "lib":      "#6b5b95",   # crt / import / eh: not decompiled
    "dxut":     "#c58b2c",   # replaced by the port, not done yet
}
LEGEND = [
    ("verified", "verified"), ("readable", "readable"), ("replaced", "replaced by port"),
    ("todo", "to do"), ("dxut", "DXUT (to replace)"), ("lib", "CRT / imports (not decompiled)"),
]


def color(r):
    if r["status"] in ("verified", "readable", "replaced", "dropped"):
        return COLORS[r["status"]]
    if r["category"] in ("crt", "import", "eh"):
        return COLORS["lib"]
    if r["category"] == "dxut":
        return COLORS["dxut"]
    return COLORS["todo"]


def render(rows):
    m = measure(rows)
    rows = sorted(rows, key=lambda r: int(r["addr"], 16))
    cells = []
    for r in rows:
        n = max(1, round(int(r["size"]) / CELL_BYTES))
        cells += [color(r)] * n
    lines = (len(cells) + COLS - 1) // COLS
    w = PAD * 2 + COLS * CELL
    h = HEADER + lines * CELL + PAD + 24
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
           f'viewBox="0 0 {w} {h}" font-family="Segoe UI, Helvetica, Arial, sans-serif">',
           f'<rect width="{w}" height="{h}" fill="#16181d"/>',
           f'<text x="{PAD}" y="26" fill="#e8eaed" font-size="16" font-weight="600">'
           f'Manhunt 2 PC decompilation</text>']

    bw = w - PAD * 2
    for i, (label, p) in enumerate((("readable", m["decomp_pct"]), ("verified", m["verified_pct"]))):
        y = 40 + i * 22
        out.append(f'<rect x="{PAD}" y="{y}" width="{bw}" height="14" rx="3" fill="#3a3f4b"/>')
        out.append(f'<rect x="{PAD}" y="{y}" width="{bw * p / 100:.2f}" height="14" rx="3" '
                   f'fill="{COLORS[label]}"/>')
        out.append(f'<text x="{PAD + 6}" y="{y + 11}" fill="#e8eaed" font-size="11">'
                   f'game code {label}: {p:.2f} %</text>')

    # One rect per run of equal colors within a row keeps the file small.
    for row in range(lines):
        seg = cells[row * COLS:(row + 1) * COLS]
        start = 0
        for i in range(1, len(seg) + 1):
            if i == len(seg) or seg[i] != seg[start]:
                x = PAD + start * CELL
                y = HEADER + row * CELL
                out.append(f'<rect x="{x}" y="{y}" width="{(i - start) * CELL - 1}" '
                           f'height="{CELL - 1}" fill="{seg[start]}"/>')
                start = i

    ly = HEADER + lines * CELL + PAD
    x = PAD
    for key, text in LEGEND:
        out.append(f'<rect x="{x}" y="{ly}" width="10" height="10" fill="{COLORS[key]}"/>')
        out.append(f'<text x="{x + 14}" y="{ly + 9}" fill="#bdc1c6" font-size="11">{text}</text>')
        x += 14 + 7 * len(text) + 16
    out.append(f'<text x="{PAD}" y="{ly + 22}" fill="#80868b" font-size="10">'
               f'One cell = {CELL_BYTES} bytes of code, in address order. Generated by '
               f'tools/progress_svg.py from decomp/functions.tsv.</text>')
    out.append("</svg>")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--svg", default=os.path.join(ROOT, "docs", "img", "progress.svg"))
    a = ap.parse_args()
    os.makedirs(os.path.dirname(os.path.abspath(a.svg)), exist_ok=True)
    with open(a.svg, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(load(TRACK)))
    print("wrote", os.path.relpath(a.svg, ROOT))


if __name__ == "__main__":
    main()
